// Generate the marketing site's changelog data from the repository CHANGELOG.md.
//
// The repository file stays the single source of truth. This script parses the
// Keep a Changelog shape into typed data the React page can render, and writes
// `src/pages/changelog/changelog.generated.ts`.
//
//   node scripts/sync-changelog.mjs            write the generated module
//   node scripts/sync-changelog.mjs --check    fail if the committed copy is stale
//
// The site builds as its own Vercel project with `site/` as the root, so the
// generated module is committed; `--check` keeps it honest.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(siteDir, '..', 'CHANGELOG.md');
const targetPath = join(siteDir, 'src', 'pages', 'changelog', 'changelog.generated.ts');

const RELEASE = /^##\s+\[?([^\]\s]+)\]?(?:\s+-\s+(\d{4}-\d{2}-\d{2}))?\s*$/;
const SECTION = /^###\s+(.+?)\s*$/;
const LINK_DEFINITION = /^\[[^\]]+\]:\s+\S+/;

export function parseChangelog(markdown) {
  const releases = [];
  let release = null;
  let section = null;

  for (const raw of markdown.split(/\r?\n/)) {
    const line = raw.trimEnd();
    if (LINK_DEFINITION.test(line)) continue;

    const releaseMatch = line.match(RELEASE);
    if (releaseMatch) {
      release = {
        version: releaseMatch[1],
        date: releaseMatch[2] ?? null,
        unreleased: releaseMatch[1].toLowerCase() === 'unreleased',
        sections: [],
      };
      releases.push(release);
      section = null;
      continue;
    }

    if (!release) continue;

    const sectionMatch = line.match(SECTION);
    if (sectionMatch) {
      section = { title: sectionMatch[1], items: [] };
      release.sections.push(section);
      continue;
    }

    if (!section) continue;

    const bullet = line.match(/^-\s+(.*)$/);
    if (bullet) {
      section.items.push(bullet[1]);
      continue;
    }

    // A wrapped bullet continues on an indented line.
    if (line.startsWith('  ') && section.items.length > 0) {
      section.items[section.items.length - 1] += ` ${line.trim()}`;
    }
  }

  return releases;
}

function render(releases) {
  return `// Generated from CHANGELOG.md by site/scripts/sync-changelog.mjs.
// Do not edit this file; edit the source document and run the script.

export interface ChangelogSection {
  title: string;
  items: string[];
}

export interface ChangelogRelease {
  version: string;
  date: string | null;
  unreleased: boolean;
  sections: ChangelogSection[];
}

export const CHANGELOG: ChangelogRelease[] = ${JSON.stringify(releases, null, 2)};
`;
}

const markdown = await readFile(sourcePath, 'utf8');
const next = render(parseChangelog(markdown));

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(targetPath, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== next) {
    console.error('[changelog] generated copy is stale — run `node scripts/sync-changelog.mjs`');
    process.exit(1);
  }
  console.log('[changelog] generated copy matches CHANGELOG.md');
} else {
  await mkdir(dirname(targetPath), { recursive: true });
  await writeFile(targetPath, next);
  console.log('[changelog] wrote src/pages/changelog/changelog.generated.ts');
}
